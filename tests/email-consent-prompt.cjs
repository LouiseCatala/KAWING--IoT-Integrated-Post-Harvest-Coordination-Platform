const fs = require('node:fs');
const assert = require('node:assert/strict');
const ts = require('typescript');
const store = new Map();
global.sessionStorage = { getItem: key => store.get(key) ?? null, setItem: (key, value) => store.set(key, value), removeItem: key => store.delete(key) };
const api = {};
new Function('exports', ts.transpileModule(fs.readFileSync('src/lib/emailConsentPrompt.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText)(api);
const user = { email: 'farmer@example.test', role: 'farmer', emailNotificationConsentAsked: true, emailNotificationsEnabled: false };
assert.equal(api.takeEmailConsentPrompt(user), true, 'Previously declined users are prompted');
assert.equal(api.takeEmailConsentPrompt(user), false, 'Refresh/remount does not repeat prompt');
api.resetEmailConsentPrompt(user.email);
assert.equal(api.takeEmailConsentPrompt(user), true, 'Next login prompts again');
api.resetEmailConsentPrompt(user.email);
assert.equal(api.takeEmailConsentPrompt({...user, emailNotificationsEnabled: true}), false, 'Opted-in users are not prompted');
assert.equal(api.takeEmailConsentPrompt(user), false, 'Disabling email waits for next login');
api.resetEmailConsentPrompt(user.email);
assert.equal(api.takeEmailConsentPrompt(user), true);
assert.equal(api.takeEmailConsentPrompt({...user, email: 'buyer@example.test', role: 'agricultural_business'}), true, 'Accounts are independent');
assert.equal(api.takeEmailConsentPrompt({...user, role: 'admin'}), false);
console.log('Email consent checks passed.');
